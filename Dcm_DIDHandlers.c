/**
 * @brief   DID 0xF190 — Write VIN (Vehicle Identification Number)
 *
 * @details Accepts a 17-byte ASCII VIN from tester and stores it in NvM.
 *
 *          Pre-conditions enforced by DCM configuration (ARXML):
 *            - Active session  : Extended Diagnostic Session (0x03)
 *            - Security level  : Level 1 unlocked (seed-key completed)
 *          DCM will NOT call this function if pre-conditions are not met;
 *          it returns NRC 0x33 or 0x22 before invoking the write callout.
 *
 *          This function is responsible for:
 *            1. Validating VIN content (ISO 3779 character set)
 *            2. Storing in NvM RAM mirror
 *            3. Triggering NvM_WriteBlock for persistence
 *
 * @param   Data        [in]  17-byte VIN data from tester
 * @param   ErrorCode   [out] NRC to return on failure
 * @return  E_OK on success, E_NOT_OK with ErrorCode set on failure
 */
Std_ReturnType Dcm_WriteData_F190(
    const uint8                  *Data,
    Dcm_NegativeResponseCodeType *ErrorCode)
{
    Std_ReturnType retVal = E_OK;
    uint8          charIdx;

    /* --- Defensive NULL checks --- */
    if ((Data == NULL_PTR) || (ErrorCode == NULL_PTR))
    {
        return E_NOT_OK;
    }

    /*
     * ISO 3779 VIN character validation:
     * Valid characters: A-H, J-N, P-Z (no I, O, Q), 0-9.
     * Position 9 (check digit): 0-9 or 'X' in FMVSS 115 (US).
     * For simplicity, validate alphanumeric excluding I, O, Q.
     */
    for (charIdx = 0U; charIdx < DCM_DID_LEN_F190; charIdx++)
    {
        uint8 ch = Data[charIdx];
        boolean validChar = FALSE;

        if ((ch >= (uint8)'0') && (ch <= (uint8)'9'))
        {
            validChar = TRUE;
        }
        else if ((ch >= (uint8)'A') && (ch <= (uint8)'H'))
        {
            validChar = TRUE;
        }
        else if ((ch >= (uint8)'J') && (ch <= (uint8)'N'))
        {
            validChar = TRUE;  /* skip I */
        }
        else if ((ch >= (uint8)'P') && (ch <= (uint8)'Z'))
        {
            /* skip O (0x4F) and Q (0x51) */
            if ((ch != (uint8)'O') && (ch != (uint8)'Q'))
            {
                validChar = TRUE;
            }
        }
        else
        {
            /* invalid character */
        }

        if (validChar == FALSE)
        {
            *ErrorCode = DCM_E_REQUEST_OUT_OF_RANGE;
            retVal = E_NOT_OK;
            break;
        }
    }

    if (retVal == E_OK)
    {
        /* Copy into local RAM mirror */
        (void)memcpy(Dcm_VinBuffer, Data, DCM_DID_LEN_F190);

        /* Trigger asynchronous NvM write — persists on next NvM cycle */
        if (NvM_WriteBlock(DCM_NVM_BLOCK_VIN, Dcm_VinBuffer) != E_OK)
        {
            *ErrorCode = DCM_E_CONDITIONS_NOT_CORRECT;
            retVal     = E_NOT_OK;
        }
    }

    return retVal;
}

