/**
 * @brief   DID 0x2001 — Engine RPM
 * @details 2 bytes uint16, MSB first.
 *          Physical value [rpm] = Raw × 0.25
 *          Raw = Physical / 0.25 = Physical × 4
 *          Range: 0–16383.75 rpm. Raw range: 0x0000–0xFFFF.
 * @param   Data    [out] 2-byte response buffer
 * @return  E_OK / E_NOT_OK
 */
Std_ReturnType Dcm_ReadData_2001(uint8 *Data)
{
    uint16         engSpeedRpm;   /* Physical value in rpm × 4 (raw) */
    Std_ReturnType retVal;

    DCM_RETURN_IF_NULL(Data);

    retVal = Rte_Read_EngSpeed_val(&engSpeedRpm);

    if (retVal == E_OK)
    {
        /* Raw = Physical_rpm × 4 (resolution 0.25 rpm/bit) */
        DCM_WRITE_UINT16_BE(Data, 0U, engSpeedRpm);
    }
    else
    {
        DCM_WRITE_UINT16_BE(Data, 0U, 0xFFFFU); /* invalid marker */
    }

    return retVal;
}

/**
 * @brief   DID 0x2002 — Engine Coolant Temperature
 * @details 1 byte uint8.
 *          Physical [°C] = Raw - 40
 *          Raw = Physical + 40. Range: -40°C (0x00) to +215°C (0xFF).
 * @param   Data    [out] 1-byte response buffer
 * @return  E_OK / E_NOT_OK
 */
Std_ReturnType Dcm_ReadData_2002(uint8 *Data)
{
    sint16         coolantTemp_degC;
    Std_ReturnType retVal;

    DCM_RETURN_IF_NULL(Data);

    retVal = Rte_Read_CoolantTemp_val(&coolantTemp_degC);

    if (retVal == E_OK)
    {
        sint16 rawVal = coolantTemp_degC + 40;

        if (rawVal < 0)       { rawVal = 0; }
        if (rawVal > 255)     { rawVal = 255; }

        Data[0] = (uint8)rawVal;
    }
    else
    {
        Data[0] = 0xFFU; /* invalid marker */
    }

    return retVal;
}

