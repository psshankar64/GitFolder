/**
 * @brief   DID 0xF186 — Active Diagnostic Session
 * @details Returns the currently active DCM session type.
 *          1 byte: 0x01=Default, 0x02=Programming, 0x03=Extended.
 * @param   Data    [out] 1-byte response buffer
 * @return  E_OK on success, E_NOT_OK on failure
 */
Std_ReturnType Dcm_ReadData_F186(uint8 *Data)
{
    Dcm_SesCtrlType currentSession;
    Std_ReturnType  retVal;

    DCM_RETURN_IF_NULL(Data);

    retVal = Dcm_GetSesCtrlType(&currentSession);

    if (retVal == E_OK)
    {
        Data[0] = (uint8)currentSession;
    }
    else
    {
        Data[0] = (uint8)DCM_DEFAULT_SESSION;
        retVal  = E_NOT_OK;
    }

    return retVal;
}

