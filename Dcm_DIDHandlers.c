/**
 * @brief   Write a uint16 value MSB-first into a byte buffer at offset.
 * @param   buf     Pointer to destination byte buffer
 * @param   offset  Byte offset in buffer
 * @param   val     uint16 value to encode
 */
#define DCM_WRITE_UINT16_BE(buf, offset, val)                   \
    do {                                                        \
        (buf)[(offset)]     = (uint8)(((val) >> 8U) & 0xFFU);  \
        (buf)[(offset) + 1U] = (uint8)((val) & 0xFFU);         \
    } while (0)

/**
 * @brief   Write a uint32 value MSB-first into a byte buffer at offset.
 */
#define DCM_WRITE_UINT32_BE(buf, offset, val)                           \
    do {                                                                \
        (buf)[(offset)]      = (uint8)(((val) >> 24U) & 0xFFU);        \
        (buf)[(offset) + 1U] = (uint8)(((val) >> 16U) & 0xFFU);        \
        (buf)[(offset) + 2U] = (uint8)(((val) >>  8U) & 0xFFU);        \
        (buf)[(offset) + 3U] = (uint8)((val) & 0xFFU);                 \
    } while (0)

/**
 * @brief   NULL pointer guard — returns E_NOT_OK if ptr is NULL.
 *          Used at function entry per AUTOSAR defensive programming.
 */
#define DCM_RETURN_IF_NULL(ptr)                                         \
    do {                                                                \
        if ((ptr) == NULL_PTR) {                                        \
            Det_ReportError(DCM_MODULE_ID, 0U,                         \
                            DCM_E_PARAM_POINTER, DCM_E_PARAM_POINTER); \
            return E_NOT_OK;                                            \
        }                                                               \
    } while (0)

