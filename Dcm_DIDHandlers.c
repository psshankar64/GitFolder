/**
 * @brief   Initialise all DID handler RAM buffers from NvM.
 *
 * @details This function must be called after NvM_ReadAll() completes
 *          (i.e., in the EcuM run phase, before DCM main function starts).
 *          It copies NvM block contents into local RAM mirrors used by
 *          all async DID read handlers.
 *
 *          Non-NvM buffers (const flash symbols) require no init here.
 *
 * @return  void
 */
void Dcm_DIDHandlers_Init(void)
{
    /* NvM blocks should already be loaded by NvM_ReadAll().
     * RAM mirrors (Dcm_VinBuffer etc.) are mapped directly to NvM
     * RAM block addresses via DaVinci NvM configuration.
     * If using separate mirrors, copy here:
     *
     * (void)memcpy(Dcm_VinBuffer,
     *              NvM_VIN_Block,
     *              DCM_DID_LEN_F190);
     * etc.
     *
     * In Vector MICROSAR, NvM_Cfg.c maps the NvM RAM block pointer
     * directly to Dcm_VinBuffer — so no explicit copy is needed here
     * when NvMRamBlockDataAddress = &Dcm_VinBuffer in ARXML.
     */

    /* Safety: zero-initialise any buffer not backed by NvM at first use */
    (void)memset(Dcm_VinBuffer,          0x20U, DCM_DID_LEN_F190); /* ASCII space default */
    (void)memset(Dcm_EcuSerialBuffer,    0x20U, DCM_DID_LEN_F18C);
    (void)memset(Dcm_BootSwFpBuffer,     0x00U, DCM_DID_LEN_F183);
    (void)memset(Dcm_AppSwFpBuffer,      0x00U, DCM_DID_LEN_F184);
    (void)memset(Dcm_AppDataFpBuffer,    0x00U, DCM_DID_LEN_F185);
    (void)memset(Dcm_MfgDateBuffer,      0x00U, DCM_DID_LEN_F18B);
    (void)memset(Dcm_ProgDateBuffer,     0x00U, DCM_DID_LEN_F1A2);
    (void)memset(Dcm_ResetCounterBuffer, 0x00U, DCM_DID_LEN_D003);
    (void)memset(Dcm_ResetCauseBuffer,   DCM_RESET_CAUSE_UNKNOWN, DCM_DID_LEN_D004);
    (void)memset(Dcm_NvmWriteCtrBuffer,  0x00U, DCM_DID_LEN_D005);
}
